// Writes dist/previews/index.html: a self-contained development page (no external
// libraries or network resources) that references the generated SVG and PNG files.

import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { tokens } from '../src/svg-helpers.mjs';
import { layout } from '../src/structural-definitions.mjs';
import { buildCatalog, distDir, isIcon } from '../src/asset-catalog.mjs';
import { dateOverlaySvg } from '../src/date-definitions.mjs';

const { background, primary, secondary, accent } = tokens.color;
const face = tokens.watchFace.size;
const catalog = buildCatalog();
const icons = catalog.filter(isIcon);
const structural = catalog.filter((a) => !isIcon(a));

const img = (src, size, alt) =>
  `<img src="../${src}" width="${size}" height="${size}" alt="${alt}">`;
const box = (a) => `left:${a.x}px;top:${a.y}px;width:${a.width}px;height:${a.height}px`;

const iconCard = (icon) => `      <figure class="card">
        <div class="sizes">
${tokens.icon.previewSizes
  .map((s) => `          <span>${img(icon.svgPath, s, `${icon.name} ${s}px`)}<small>${s}</small></span>`)
  .join('\n')}
        </div>
        <figcaption>${icon.name}.svg</figcaption>
      </figure>`;

const iconSection = (title, category) => `    <h2>${title}</h2>
    <div class="grid">
${icons.filter((i) => i.category === category).map(iconCard).join('\n')}
    </div>`;

const structuralCard = (asset) => `      <figure class="card">
        <div class="checker">${img(asset.svgPath, 225, asset.name)}</div>
        <figcaption>${asset.name}.svg &middot; ${asset.width}&times;${asset.height}${
  asset.transparent ? ' &middot; transparent' : ''
}</figcaption>
      </figure>`;

// Sample content for the mock only; none of this text exists in the assets.
const moduleSamples = [
  ['heart', '072'],
  ['battery', '84%'],
  ['weather-partly-cloudy', '18&deg;'],
];
// Approximate bottom of the placeholder clock digits, which are HTML text in the page font.
const CLOCK_INK_BOTTOM = 184;

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Syswatch 01 asset preview</title>
<style>
  :root { color-scheme: dark; }
  body { margin: 0; padding: 24px; background: ${background}; color: ${primary};
    font: 13px/1.5 Consolas, "Lucida Console", monospace; }
  h1 { font-size: 18px; letter-spacing: 2px; text-transform: uppercase; margin: 0 0 4px; }
  h2 { font-size: 13px; letter-spacing: 2px; text-transform: uppercase; color: ${accent};
    border-bottom: 1px solid ${secondary}; padding-bottom: 4px; margin: 32px 0 16px; }
  p { color: ${secondary}; margin: 0; max-width: 70ch; }
  .grid { display: flex; flex-wrap: wrap; gap: 12px; }
  .card { margin: 0; padding: 12px; border: 1px solid ${secondary}; background: #000; }
  figcaption { margin-top: 8px; text-align: center; }
  .sizes { display: flex; align-items: flex-end; gap: 14px; }
  .sizes span { display: flex; flex-direction: column; align-items: center; gap: 4px; }
  .sizes small, .mock-note { color: ${secondary}; }
  img { display: block; }
  .checker { background: repeating-conic-gradient(#0a1420 0% 25%, #050b12 0% 50%) 0 0 / 18px 18px; }
  .faces { display: flex; flex-wrap: wrap; gap: 24px; align-items: flex-start; }
  .face { position: relative; width: ${face}px; height: ${face}px; border-radius: 50%;
    overflow: hidden; background: #000; flex: none; }
  .face > img, .face > .date { position: absolute; inset: 0; }
  .face .ring-active { clip-path: polygon(50% 50%, 50% 0, 100% 0, 100% 100%, 50% 100%); }
  .area { position: absolute; display: flex; align-items: center; justify-content: center; }
  .clock { font-size: 84px; letter-spacing: 4px; }
  .event { justify-content: flex-start; padding-left: 22px; box-sizing: border-box;
    letter-spacing: 1px; }
  .module { gap: 6px; font-size: 15px; }
</style>
</head>
<body>
  <h1>Syswatch 01 asset preview</h1>
  <p>Generated by scripts/generate-preview.mjs. Development aid only: text on this page is HTML,
    the SVG and PNG assets themselves contain none.</p>

${iconSection('Interface icons', 'icon-interface')}

${iconSection('Weather icons', 'icon-weather')}

    <h2>Structural assets</h2>
    <div class="grid">
${structural.map(structuralCard).join('\n')}
    </div>

    <h2>Composed watch face (${face}&times;${face})</h2>
    <div class="faces">
      <figure class="card">
        <div class="face">
${structural.map((a) => `          ${img(a.pngPath, face, a.name).replace('<img', `<img class="${a.name === 'seconds-ring-active' ? 'ring-active' : 'layer'}"`)}`).join('\n')}
        </div>
        <figcaption>PNG layers only &middot; active ring clipped to 30 s</figcaption>
      </figure>
      <figure class="card">
        <div class="face">
${structural.map((a) => `          ${img(a.pngPath, face, a.name).replace('<img', `<img class="${a.name === 'seconds-ring-active' ? 'ring-active' : 'layer'}"`)}`).join('\n')}
          <div class="area clock" style="${box(layout.clock)}">10:08</div>
          ${dateOverlaySvg(CLOCK_INK_BOTTOM)}
          <div class="area event" style="${box(layout.event)}">14:30 &nbsp;SYSTEM REVIEW</div>
${layout.modules
  .map(
    (m, i) =>
      `          <div class="area module" style="${box(m)}">${img(`svg/${moduleSamples[i][0]}.svg`, 28, moduleSamples[i][0])}<span>${moduleSamples[i][1]}</span></div>`,
  )
  .join('\n')}
        </div>
        <figcaption>With sample content <span class="mock-note">(placeholder HTML text and icons; date in Share Tech Mono)</span></figcaption>
      </figure>
    </div>
</body>
</html>
`;

const previewDir = join(distDir, 'previews');
mkdirSync(previewDir, { recursive: true });
writeFileSync(join(previewDir, 'index.html'), html);
console.log('wrote previews/index.html');
