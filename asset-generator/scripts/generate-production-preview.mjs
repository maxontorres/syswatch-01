// Production preview: renders the one watch face with the locked typography and writes
// dist/previews/production-preview.html. Output is deterministic. Nothing outside
// dist/previews/production-preview.* is touched.

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import sharp from 'sharp';
import { tokens } from '../src/svg-helpers.mjs';
import { distDir } from '../src/asset-catalog.mjs';
import { fontById } from '../src/font-definitions.mjs';
import {
  CLOCK_FONT, INTERFACE_FONT, PRODUCTION_TIME, buildProductionFace,
} from '../src/production-definitions.mjs';

const production = buildProductionFace();
await sharp(Buffer.from(production.faceSvg)).png({ compressionLevel: 9 }).toFile(join(distDir, production.pngPath));

const { background, primary, secondary, accent } = tokens.color;
const face = tokens.watchFace.size;
const clockFont = fontById(CLOCK_FONT);
const interfaceFont = fontById(INTERFACE_FONT);
const run = (role) => production.runs.find((r) => r.role === role);
const texts = (role) => production.runs.filter((r) => r.role === role).map((r) => r.text).join(', ');
const px = (n) => Math.round(n * 10) / 10;

const typeRow = (element, font, role, content = texts(role)) =>
  `      <tr><th>${element}</th><td>${font.family} Regular</td><td>${run(role).size} px</td><td>${content}</td></tr>`;

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Syswatch 01 production preview</title>
<style>
  :root { color-scheme: dark; }
  body { margin: 0; padding: 24px; background: ${background}; color: ${primary};
    font: 13px/1.5 Consolas, "Lucida Console", monospace; }
  h1 { font-size: 18px; letter-spacing: 2px; text-transform: uppercase; margin: 0 0 4px; }
  h2 { font-size: 13px; letter-spacing: 2px; text-transform: uppercase; color: ${accent};
    border-bottom: 1px solid ${secondary}; padding-bottom: 4px; margin: 32px 0 8px; }
  p, li { color: ${secondary}; max-width: 90ch; }
  p { margin: 0 0 16px; }
  ol { margin: 0 0 16px; padding-left: 24px; }
  nav a { color: ${primary}; margin-right: 16px; }
  .card { display: inline-block; margin: 16px 0 0; padding: 12px; border: 1px solid ${secondary}; background: #000; }
  figcaption { margin-top: 8px; }
  .note { color: ${secondary}; }
  /* The render is shown 1:1 and must never be resampled by the browser. */
  img { display: block; image-rendering: pixelated; }
  .face { width: ${face}px; height: ${face}px; border-radius: 50%; overflow: hidden; }
  table { border-collapse: collapse; margin-bottom: 16px; }
  th, td { border: 1px solid ${secondary}; padding: 4px 10px; text-align: left; }
  thead th { color: ${accent}; }
</style>
</head>
<body>
  <h1>Syswatch 01 production preview</h1>
  <p>Generated by scripts/generate-production-preview.mjs. ${clockFont.family} ${clockFont.version} by
    ${clockFont.designer} (SIL Open Font License 1.1) is the production clock font. The date, event
    text and data modules are ${interfaceFont.family} ${interfaceFont.version}. All values are sample content.</p>
  <nav><a href="clock-font.html">Clock font comparison</a><a href="index.html">Asset preview</a><a href="numeral-lab.html">Numeral lab</a></nav>

  <figure class="card">
    <div class="face"><img src="${production.name}.png" width="${face}" height="${face}" alt="${PRODUCTION_TIME.time} ${PRODUCTION_TIME.meridiem}, ${run('date').text}"></div>
    <figcaption>${face}&times;${face} px, shown 1:1 <span class="note">&middot; 12-hour clock, no leading zero</span></figcaption>
  </figure>

  <h2>Typography</h2>
  <table>
    <thead><tr><th>Element</th><th>Font</th><th>Size</th><th>Shown</th></tr></thead>
    <tbody>
${typeRow('Main clock', clockFont, 'clock')}
${typeRow('AM/PM', clockFont, 'meridiem')}
${typeRow('Date', interfaceFont, 'date')}
${typeRow('Next event', interfaceFont, 'event')}
${typeRow('Data values', interfaceFont, 'value')}
${typeRow('Data labels', interfaceFont, 'label')}
    </tbody>
  </table>
  <p>The clock is drawn from the unmodified font outlines at ${run('clock').size / clockFont.pixelsPerEm}&times; the
    ${clockFont.pixelsPerEm} px design size and AM/PM at ${run('meridiem').size / clockFont.pixelsPerEm}&times;, with
    whole-pixel glyph origins and anti-aliasing off. The date is centred on the face with
    ${px(production.date.gapAbove)} px clear above its capitals and ${px(production.date.gapBelow)} px below;
    only its separator dot is amber. Inactive seconds-ring segments are at
    ${Math.round(tokens.secondsRing.inactiveOpacity * 100)}% opacity; elapsed segments are full primary cyan.</p>

  <h2>Visual hierarchy</h2>
  <ol>
    <li>Main clock</li>
    <li>Date</li>
    <li>Next event</li>
    <li>Heart rate, battery and weather</li>
    <li>Grid and decorative HUD elements</li>
  </ol>
</body>
</html>
`;

writeFileSync(join(distDir, production.htmlPath), html);
console.log(`rendered ${production.pngPath}`);
console.log(`wrote ${production.htmlPath}`);
